# this is function definition for calculating the average of three numbers
def avg():
    a = float(input("Enter the first number: "))
    b = float(input("Enter the second number: "))
    c = float(input("Enter the third number: "))

    average = (a + b + c) / 3
    print(f"The average of {a}, {b}, and {c} is: {average:.2f}")
